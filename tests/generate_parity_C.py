#!/usr/bin/env python3
"""Generate R numerical comparisons from CURRENT live browser snapshots.

The historical generators contain model-specific checks (01-25). This script
supplies current UI values and current R exports, injects strict failure gates,
records the exact build SHA-256, and refuses missing/obsolete evidence.
Generation is not a substitute for EXECUTING both R comparison files.
"""
import csv
import hashlib
import json
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
GROUPS = [('01_16',range(1,17),'gen_verifica_R_01_16.js'),
          ('17_25',range(17,26),'gen_verifica_R.js')]
LABS = ('distribuzioni bivariata simulazione lgn-tcl adattamento stimatori fisher '
        'intervalli test regressione regressione-lp glm arma quantilica penalizzata '
        'spline segmentata validazione knn alberi boost reti-neurali pca clustering dbscan').split()

def main():
    build_sha=hashlib.sha256((ROOT/'index.html').read_bytes()).hexdigest()
    outdir=ROOT/'verifica'
    for group, idx, generator in GROUPS:
        src=outdir/f'snapshots_C_{group}.json'
        data=json.loads(src.read_text('utf-8'))
        assert data['build_sha256']==build_sha, f'{src.name}: stale build'
        ids=[LABS[i-1] for i in idx]
        assert list(data['labs'])==ids, f'{src.name}: missing/reordered labs'
        assert all(x['code'] and x['rows'] for x in data['labs'].values())
        raw=outdir/f'snapshots_C_{group}_raw.json'
        raw.write_text(json.dumps(data['labs'],ensure_ascii=False),encoding='utf-8')
        cmd=['node',str(ROOT/'tests'/generator),str(raw)]
        if group=='17_25':
            rng=subprocess.run(['node',str(ROOT/'tests/rng_per_verifica_R.js')],
                               cwd=ROOT,capture_output=True,text=True,check=True)
            rngfile=outdir/'rng_C.json'
            rngfile.write_text(rng.stdout,encoding='utf-8')
            cmd.append(str(rngfile))
        result=subprocess.run(cmd,cwd=ROOT,capture_output=True,text=True,check=True)
        output=result.stdout
        assert 'undefined' not in output and 'NaN' not in output, 'missing benchmark values'
        # A table cell such as 'premi il pulsante' is not a numerical reference:
        # fail at generation rather than executing a long R benchmark with c().
        assert not re.search(r'confronta\([^\n]*?,\s*c\(\)\s*,', output), 'empty benchmark reference c()'
        if group=='17_25':
            # The legacy runner records non-requested labs as SALTATO. In the
            # restricted 17-25 validation they are deliberately excluded, not
            # missing tests. Suppress those records, keeping a strict no-skip
            # rule for every *requested* laboratory.
            legacy='if (!is.null(SOLO) && !id %in% SOLO) { registra(id, "non richiesto (SOLO)", NA); return(NULL) }'
            assert legacy in output, 'legacy skip guard has changed'
            output=output.replace(legacy,'if (!is.null(SOLO) && !id %in% SOLO) return(NULL)')
            output='SOLO <- c(' + ', '.join('"'+x+'"' for x in ids) + ')\n' + output
        csvfile=f'verifica/runs/parita_C_{group}_esiti.csv'
        target='verifica_statatlas_01_16_esiti.csv' if group=='01_16' else 'verifica_statatlas_esiti.csv'
        assert target in output, f'{generator} changed output name'
        output=output.replace('"'+target+'"','"'+csvfile+'"')
        # The generated R benchmark must also work as a standalone Rscript run.
        # Its destination may not exist after extracting a fresh source archive.
        save='write.csv(.verifica, "'+csvfile+'", row.names = FALSE)'
        assert save in output, f'{generator}: CSV writer missing'
        output=output.replace(save, 'dir.create("verifica/runs", recursive = TRUE, showWarnings = FALSE)\n'+save)
        # Report the real output path instead of the historical default filename.
        output=output.replace('Esiti salvati in '+target, 'Esiti salvati in '+csvfile)
        output+='\n# Macrofase C strict gate: skipped, missing or mismatching checks are FAILURE.\n'
        output+='if (any(.verifica$esito != "OK") || length(unique(.verifica$lab[grepl("^[0-9][0-9]$",.verifica$lab)])) != '+str(len(ids))+') {\n'
        output+='  stop("Numerical R/JS parity not demonstrated for all expected labs")\n}\n'
        output+='cat("PARITY '+group+' PASS: '+str(len(ids))+' labs; build SHA-256 '+build_sha+'\\n")\n'
        p=outdir/f'parita_C_{group}.R'
        p.write_text('# AUTOGENERATED — do not edit; run Python generator after rebuilding.\n' +
                     '# build_sha256: '+build_sha+'\n'+output,encoding='utf-8')
        assert f'build_sha256: {build_sha}' in p.read_text('utf-8')
        print('GENERATED',p.relative_to(ROOT),'labs',len(ids),'bytes',p.stat().st_size)
    print('CAUTION: numerical equality only after two Rscript runs PASS; these are one default scenario per lab (R1 candidate, NOT R2).')
if __name__=='__main__':main()
